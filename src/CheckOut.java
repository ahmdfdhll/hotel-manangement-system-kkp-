    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String searchKey = jTextField1.getText();
        try {
            ResultSet rs = Select.getData("select * from customer where (RoomNumber='" + searchKey + "' OR Name='" + searchKey + "') and checkout is NULL");
            if (rs.next()) {
                jTextField1.setEnabled(false);
                id = rs.getInt(1);
                jTextField2.setText(rs.getString(2));
                jTextField3.setText(rs.getString(8));
                jTextField5.setText(rs.getString(3));

                // --- BAGIAN 1: HARGA (Diambil & Diformat) ---
                // Kita simpan harga aslinya di variabel 'hargaMentah'
                double hargaMentah = rs.getDouble(11);

                // Format tampilan biar ada titiknya (Contoh: 550.000)
                DecimalFormat df = new DecimalFormat("#,###");
                jTextField6.setText(df.format(hargaMentah));

                // --- BAGIAN 2: HITUNG TANGGAL ---
                SimpleDateFormat myFormat = new SimpleDateFormat("yyyy/MM/dd");
                Calendar cal = Calendar.getInstance();
                jTextField4.setText(myFormat.format(cal.getTime()));

                String dateBeforeString = rs.getString(8);
                java.util.Date dateBefore = myFormat.parse(dateBeforeString);
                String dateAfterString = myFormat.format(cal.getTime());
                java.util.Date dateAfter = myFormat.parse(dateAfterString);

                long difference = dateAfter.getTime() - dateBefore.getTime();
                int noOfDayStay = (int) (difference / (1000 * 60 * 60 * 24));
                if (noOfDayStay == 0) {
                    noOfDayStay = 1;
                }

                jTextField7.setText(String.valueOf(noOfDayStay));

                // --- BAGIAN 3: PERBAIKAN TOTAL HARGA (PENTING!) ---
                // JANGAN ambil dari jTextField6.getText() karena itu ada titiknya (bikin error hitungan)
                // GUNAKAN 'hargaMentah' yang murni dari database
                double totalHitungan = noOfDayStay * hargaMentah; // Hitung pakai angka murni

                // Baru hasilnya diformat titiknya saat ditampilkan
                jTextField8.setText(df.format(totalHitungan));

                jTextField9.setText(rs.getString(6));
                RoomType = rs.getString(9);
            } else {
                JOptionPane.showMessageDialog(null, "Room Number is not Booked or does not exist");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    public void hitungUlang() {
        try {
            // 1. Ambil Data Harga & Tanggal
            String hargaText = jTextField6.getText().replace(".", "").replace(",", "");
            double harga = Double.parseDouble(hargaText);
            String checkIn = jTextField3.getText();
            String checkOut = jTextField4.getText(); // Ini yang kamu edit

            // 2. Hitung Durasi Hari (Berdasarkan Tanggal Check Out Baru)
            java.text.SimpleDateFormat format = new java.text.SimpleDateFormat("yyyy/MM/dd");
            java.util.Date d1 = format.parse(checkIn);
            java.util.Date d2 = format.parse(checkOut);

            long diff = d2.getTime() - d1.getTime();
            int hari = (int) (diff / (1000 * 60 * 60 * 24));

            if (hari <= 0) {
                hari = 1;
            } // Minimal 1 hari

            // 3. Update Kolom Jumlah Hari & Total
            jTextField7.setText(String.valueOf(hari)); // Update Number of Days
            jTextField8.setText(String.valueOf(hari * harga)); // Update Total Amount
            double total = hari * harga;
            DecimalFormat df = new DecimalFormat("#,###"); // Format polos
            jTextField8.setText(df.format(total));
        } catch (Exception e) {
            // Error diamkan saja (misal user belum selesai ngetik tanggal)
        }
    }

