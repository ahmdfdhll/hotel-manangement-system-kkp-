    public void addInfoRow(PdfPTable table, String label, String value, com.lowagie.text.Font fontLabel, com.lowagie.text.Font fontValue) {
        PdfPCell c1 = new PdfPCell(new Paragraph(label, fontLabel));
        c1.setBorder(PdfPCell.NO_BORDER);
        table.addCell(c1);

        PdfPCell c2 = new PdfPCell(new Paragraph(value, fontValue));
        c2.setBorder(PdfPCell.NO_BORDER);
        table.addCell(c2);
    }

    public void addHeaderCell(PdfPTable table, String title) {
        com.lowagie.text.Font fontHeader = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10);
        PdfPCell cell = new PdfPCell(new Paragraph(title, fontHeader));
        cell.setBackgroundColor(java.awt.Color.LIGHT_GRAY);
        cell.setHorizontalAlignment(Element.ALIGN_CENTER);
        cell.setPadding(5);
        table.addCell(cell);
    }

