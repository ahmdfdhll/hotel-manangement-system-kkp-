    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int id = 1;
        String name = jTextField1.getText();
        String MobileNumber = jTextField2.getText();
        String Address = jTextField3.getText();
        String Gender = (String) jComboBox1.getSelectedItem();
        String Email = jTextField4.getText();
        String IDProof = jTextField5.getText();
        String CheckIN = jTextField6.getText();
        String RoomNumber = (String) jComboBox3.getSelectedItem();
        String Price = jTextField7.getText(); // Ini adalah Harga Per Malam (Per Hari)

        // --- LOGIKA BREAKFAST (HARGA PER HARI) ---
        String AsliRoomType = (String) jComboBox2.getSelectedItem();
        String statusBreakfast = (String) jComboBox4.getSelectedItem();

        String RoomTypeUntukDB = AsliRoomType;
        String FinalPricePerDay = Price; // Harga Akhir Per Hari

        if (statusBreakfast != null) {

            // 1. SKENARIO YES (Tulisan "+ Breakfast" & Harga Dasar Naik 50.000)
            if (statusBreakfast.equals("Yes")) {
                RoomTypeUntukDB = AsliRoomType + " + Breakfast";

                try {
                    // Kita naikkan HARGA DASAR-nya.
                    // Nanti sistem CheckOut yang akan mengalikan dengan jumlah hari menginap.
                    double hargaDasar = Double.parseDouble(Price);
                    hargaDasar = hargaDasar + 50000; // Tambah 50rb per hari
                    FinalPricePerDay = String.valueOf((int) hargaDasar);
                } catch (Exception e) {
                    System.out.println("Error hitung harga: " + e.getMessage());
                }
            } // 2. SKENARIO FREE (Tulisan "+ Breakfast", Harga Dasar TETAP)
            else if (statusBreakfast.equals("Free")) {
                RoomTypeUntukDB = AsliRoomType + " + Breakfast";
            }

            // 3. SKENARIO NO (Tidak ada perubahan)
        }

        // ---------------------------------------------
        String Query = "select max(id) from customer";
        try {
            ResultSet rs = Select.getData(Query);
            while (rs.next()) {
                id = rs.getInt(1);
            }
            id = id + 1;

            if (!Price.equals("")) {
                // Update status kamar
                Query = "update room set status='Booked' where RoomNumber='" + RoomNumber + "'";
                InsertUpdateDelete.setData(Query, "");

                // Simpan ke Database
                // Kita simpan FinalPricePerDay (Harga yang sudah dinaikkan 50rb)
                Query = "insert into customer(id,Name,MobileNumber,Address,Gender,Email,IDProof,CheckIN,RoomType,RoomNumber,Price) values('" + id + "','" + name + "','" + MobileNumber + "','" + Address + "','" + Gender + "','" + Email + "','" + IDProof + "','" + CheckIN + "','" + RoomTypeUntukDB + "','" + RoomNumber + "','" + FinalPricePerDay + "')";

                InsertUpdateDelete.setData(Query, "Customer Check IN Successfully");
                setVisible(false);
                new CheckIN().setVisible(true);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }


    }//GEN-LAST:event_jButton2ActionPerformed

