    public void showRoomInTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Hapus data lama di tabel

        try {
            // Ambil tipe kamar yang dipilih
            String roomType = (String) jComboBox2.getSelectedItem();

            // Query database (Pastikan nama kolom: roomnumber, roomtype, price, status)
            ResultSet rs = Select.getData("SELECT * FROM room");

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("roomnumber"),
                    rs.getString("roomtype"),
                    rs.getString("price"),
                    rs.getString("status")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

