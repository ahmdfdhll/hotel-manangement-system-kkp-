    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        String roomNo = jTextField1.getText();

        if (roomNo.equals("")) {
            javax.swing.JOptionPane.showMessageDialog(null, "Silakan klik baris kamar di tabel terlebih dahulu!");
            return;
        }

        javax.swing.JPopupMenu popup = new javax.swing.JPopupMenu();

        javax.swing.JMenuItem itemMaintenance = new javax.swing.JMenuItem("Ubah status ke: MAINTENANCE");
        javax.swing.JMenuItem itemAvailable = new javax.swing.JMenuItem("Ubah status ke: AVAILABLE");

        // --- AKSI 1: PILIH MAINTENANCE ---
        itemMaintenance.addActionListener(new java.awt.event.ActionListener() {
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                try {
                    // Update Database ke 'Maintenance'
                    String query = "UPDATE room SET status='Maintenance' WHERE roomNumber='" + roomNo + "'";
                    Project.InsertUpdateDelete.setData(query, "Sukses! Kamar " + roomNo + " sekarang statusnya MAINTENANCE.");

                    // Refresh Halaman
                    setVisible(false);
                    new ManageRoom().setVisible(true);
                } catch (Exception e) {
                    javax.swing.JOptionPane.showMessageDialog(null, e);
                }
            }
        });

        // --- AKSI 2: PILIH AVAILABLE ---
        itemAvailable.addActionListener(new java.awt.event.ActionListener() {
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                try {
                    // Update Database ke 'Available'
                    String query = "UPDATE room SET status='Available' WHERE roomNumber='" + roomNo + "'";
                    Project.InsertUpdateDelete.setData(query, "Sukses! Kamar " + roomNo + " sekarang statusnya AVAILABLE.");

                    // Refresh Halaman
                    setVisible(false);
                    new ManageRoom().setVisible(true);
                } catch (Exception e) {
                    javax.swing.JOptionPane.showMessageDialog(null, e);
                }
            }
        });

        // Masukkan item ke dalam Popup
        popup.add(itemMaintenance);
        popup.add(itemAvailable);

        // ====================================================================
        // MUNCULKAN POPUP TEPAT DI BAWAH TOMBOL UPDATE
        // ====================================================================
        // (0, tinggi tombol) artinya muncul pas di bawah tombolnya
        popup.show(jButton4, 0, jButton4.getHeight());
    }//GEN-LAST:event_jButton4ActionPerformed

