    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String roomNumber = jTextField1.getText();

        if (roomNumber.equals("")) {
            JOptionPane.showMessageDialog(null, "Please Enter Room Number to Delete");
        } else {
            try {

                java.sql.ResultSet rs = Project.Select.getData("SELECT * FROM room WHERE RoomNumber='" + roomNumber + "'");

                if (rs.next()) {

                    String status = rs.getString("status");

                    if (status.equals("Booked")) {
                        JOptionPane.showMessageDialog(null, "Gagal Hapus! Kamar " + roomNumber + " sedang terisi (Booked).");
                    } else {
                        // 4. Jika status 'Not Booked', baru tanya konfirmasi hapus
                        int a = JOptionPane.showConfirmDialog(null, "Do you really want to Delete Room " + roomNumber + "?", "Select", JOptionPane.YES_NO_OPTION);

                        if (a == 0) { // Jika pilih YES
                            // Jalankan perintah Hapus
                            Project.InsertUpdateDelete.setData("DELETE FROM room WHERE RoomNumber='" + roomNumber + "'", "Room Deleted Successfully");

                            // Refresh Halaman
                            setVisible(false);
                            new ManageRoom().setVisible(true);
                        }
                    }
                } else {
                    JOptionPane.showMessageDialog(null, "Room Number does not exist");
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

